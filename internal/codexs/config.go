package codexs

import (
	"strconv"
	"strings"
)

// Codex provider configuration. These values are the single source of truth
// for both the generated config.toml (renderCodexConfig) and the inline
// `-c key=value` overrides passed on the codex command line (codexConfigArgs).
const (
	credentialsStore = "file"
	providerName     = "profile"
	providerWireAPI  = "responses"
)

const configHeader = "# Generated by codexs. Edit the profile with `codexs update`."

const providerTable = "model_providers.profile"

// topLevelSettings returns the root-level config keys in (key, value) form,
// where value is an already-encoded TOML token.
func topLevelSettings() [][2]string {
	return [][2]string{
		{"cli_auth_credentials_store", tomlString(credentialsStore)},
		{"model_provider", tomlString(providerName)},
	}
}

// providerSettings returns the keys under the [model_providers.profile] table.
func providerSettings(baseURL string) [][2]string {
	return [][2]string{
		{"name", tomlString(providerName)},
		{"wire_api", tomlString(providerWireAPI)},
		{"base_url", tomlString(baseURL)},
		{"requires_openai_auth", "true"},
	}
}

func renderCodexConfig(baseURL string) string {
	var b strings.Builder
	b.WriteString(configHeader)
	b.WriteByte('\n')
	for _, kv := range topLevelSettings() {
		b.WriteString(kv[0])
		b.WriteString(" = ")
		b.WriteString(kv[1])
		b.WriteByte('\n')
	}
	b.WriteByte('\n')
	b.WriteString("[" + providerTable + "]\n")
	for _, kv := range providerSettings(baseURL) {
		b.WriteString(kv[0])
		b.WriteString(" = ")
		b.WriteString(kv[1])
		b.WriteByte('\n')
	}
	return b.String()
}

// codexConfigArgs returns the inline `-c key=value` overrides for the codex
// command line, derived from the same settings as renderCodexConfig.
func codexConfigArgs(baseURL string) []string {
	var args []string
	for _, kv := range topLevelSettings() {
		args = append(args, "-c", kv[0]+"="+kv[1])
	}
	for _, kv := range providerSettings(baseURL) {
		args = append(args, "-c", providerTable+"."+kv[0]+"="+kv[1])
	}
	return args
}

func tomlString(value string) string {
	return strconv.Quote(value)
}
